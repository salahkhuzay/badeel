def patch(brand_id: str, new_body: str):
    global s
    pat = re.compile(
        r'(id: "%s",.*?models: \[\n)(.*?)(\n    \],)' % brand_id, re.S
    )
    m = pat.search(s)
    assert m, brand_id
    s = s[: m.start(2)] + new_body + s[m.start(3):]

for bid, body in [
    ("apple", APPLE),
    ("samsung", SAMSUNG),
    ("huawei", HUAWEI),
    ("xiaomi", XIAOMI),
    ("infinix", INFINIX),
]:
    patch(bid, body)

