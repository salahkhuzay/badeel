/* ==========================================================================
   qa/wave19-phones.ts — موجة 19: موديلات الهواتف الشاملة
   --------------------------------------------------------------------------
   ① موديلات آيفون المطلوبة حرفياً من المستخدم (11–18 برو ماكس، 16/17 بلس،
      17e، Air، Duo) موجودة بأسمائها ومعرفاتها.
   ② تصحيح خطأ قديم: معرف iphone-16 كان اسمه «آيفون 16 برو ماكس».
   ③ شمولية سامسونغ/شاومي/إنفينيكس/هواوي: سلاسل A/S/نوت/Z/M، ريدمي/نوت/بوكو/مي،
      سمارت/هوت/نوت/زيرو/GT، Y/P/ميت/نوفا — مع وحدانية المعرفات والأسماء.
   التشغيل: ./node_modules/.bin/tsx qa/wave19-phones.ts
   ========================================================================== */

import { ALL_BRANDS } from "../lib/brands";

let pass = 0;
let fail = 0;
const ok = (label: string, cond: boolean, extra = "") => {
  cond ? pass++ : fail++;
  console.log(`${cond ? "✅" : "❌"} ${label}${extra ? ` — ${extra}` : ""}`);
};

const brand = (id: string) => ALL_BRANDS.find((b) => b.id === id)!;
const names = (id: string) => brand(id).models.map((m) => m.name);
const ids = (id: string) => brand(id).models.map((m) => m.id);
const has = (b: string, ...needles: string[]) => {
  const t = names(b).join(" | ");
  return needles.every((n) => t.includes(n));
};

/* ─────────── ① آيفون: قائمة المستخدم حرفياً ─────────── */
const appleWanted = [
  "آيفون 11 برو ماكس",
  "آيفون 12 برو ماكس",
  "آيفون 13 برو ماكس",
  "آيفون 14 برو ماكس",
  "آيفون 15 برو ماكس",
  "آيفون 16 بلس",
  "آيفون 17",
  "آيفون 17 بلس",
  "آيفون 17e",
  "آيفون 17 برو",
  "آيفون 17 برو ماكس",
  "آيفون Duo",
  "آيفون 18 برو",
  "آيفون 18 برو ماكس",
  "آيفون Air",
];
ok(
  "آيفون: كل الموديلات المطلوبة موجودة (15)",
  has("apple", ...appleWanted),
  appleWanted.filter((n) => !names("apple").includes(n)).join("، ")
);
ok(
  "تصحيح: iphone-16 اسمه «آيفون 16» لا برو ماكس",
  brand("apple").models.find((m) => m.id === "iphone-16")?.name === "آيفون 16"
);
ok(
  "آيفون: برو ماكس موجود لكل جيل 16 أيضاً",
  names("apple").includes("آيفون 16 برو ماكس")
);

/* ─────────── ③ شمولية الماركات الأربع ─────────── */
ok(
  "سامسونغ: سلسلة A واسعة (A01…A73)",
  has("samsung", "جالاكسي A01", "جالاكسي A15", "جالاكسي A35", "جالاكسي A55", "جالاكسي A71", "جالاكسي A73")
);
ok(
  "سامسونغ: سلسلة S كاملة مع ألترا وبلس وFE",
  has("samsung", "جالاكسي S21 ألترا", "جالاكسي S22 ألترا", "جالاكسي S23 ألترا", "جالاكسي S24 ألترا", "جالاكسي S25 ألترا", "جالاكسي S20 FE", "جالاكسي S24 FE")
);
ok(
  "سامسونغ: نوت بألترا + Z فولد/فليب + M",
  has("samsung", "نوت 20 ألترا", "جالاكسي Z فولد 5", "جالاكسي Z فليب 5", "جالاكسي M51", "جالاكسي M31")
);
ok(
  "شاومي: ريدمي + نوت برو + بوكو X/F + مي",
  has("xiaomi", "ريدمي 14", "ريدمي نوت 13 برو", "بوكو X6 برو", "بوكو F6", "شاومي 14", "ريدمي 9A")
);
ok(
  "إنفينيكس: سمارت/هوت/نوت/زيرو/GT",
  has("infinix", "سمارت 8", "هوت 30", "هوت 40", "نوت 30", "نوت 40 برو", "زيرو 30", "GT 20 برو")
);
ok(
  "هواوي: Y/P/ميت/نوفا + بورا",
  has("huawei", "Y9s", "P30 برو", "ميت 40", "ميت 60", "نوفا 12", "بورا 70", "نوفا 3i")
);

/* ─────────── سلامة المعرفات والأسماء ─────────── */
for (const b of ["apple", "samsung", "xiaomi", "infinix", "huawei"]) {
  const i = ids(b);
  const n = names(b);
  ok(
    `${b}: معرفات وأسماء بلا تكرار (${i.length} موديلاً)`,
    new Set(i).size === i.length && new Set(n).size === n.length
  );
}

console.log(`\n══ النتيجة: ${pass} نجاح · ${fail} فشل ══`);
process.exit(fail === 0 ? 0 : 1);
